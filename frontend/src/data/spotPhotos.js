export function resolveSpotPhotoUrl(path, baseUrl) {
  if (!path) return ''
  return `${baseUrl ?? import.meta.env.BASE_URL}${path.replace(/^\/+/, '')}`
}

export function getSpotPhoto(spotName) {
  const photo = spotPhotoManifest[spotName]
  if (!photo) return null

  return {
    ...photo,
    src: resolveSpotPhotoUrl(photo.path),
  }
}
